import { Type } from "typebox";

const key = Type.String({ minLength: 1, maxLength: 80, pattern: "^[A-Za-z0-9_-]+$" });
const title = Type.String({ minLength: 1, maxLength: 300 });
const draftKey = Type.String({ minLength: 1, maxLength: 75, pattern: "^[A-Za-z0-9_-]+$" });
const optionalText = () => Type.Optional(Type.String({ maxLength: 300 }));
const reference = Type.Union([
	Type.Object({ new_node: draftKey }, { additionalProperties: false }),
	Type.Object({ node_id: key }, { additionalProperties: false }),
]);
const node = Type.Union([
	Type.Object(
		{ key: draftKey, kind: Type.Literal("paper"), paper_id: Type.String({ minLength: 1, maxLength: 200 }) },
		{ additionalProperties: false },
	),
	Type.Object(
		{ key: draftKey, kind: Type.Literal("text"), title, content: Type.String({ maxLength: 20000 }) },
		{ additionalProperties: false },
	),
	Type.Object(
		{
			key: draftKey,
			kind: Type.Literal("author"),
			title,
			research_area: optionalText(),
			organization: optionalText(),
			profile_url: Type.Optional(Type.String({ maxLength: 2048 })),
		},
		{ additionalProperties: false },
	),
	Type.Object(
		{
			key: draftKey,
			kind: Type.Literal("team"),
			title,
			institution: optionalText(),
			leader_name: optionalText(),
			research_areas: Type.Optional(Type.String({ maxLength: 500 })),
			homepage_url: Type.Optional(Type.String({ maxLength: 2048 })),
			members: Type.Optional(Type.Array(Type.String({ minLength: 1, maxLength: 120 }), { maxItems: 100 })),
		},
		{ additionalProperties: false },
	),
]);

export const canvasNodeProposalSchema = Type.Object(
	{
		request_id: Type.String({
			minLength: 1,
			maxLength: 80,
			pattern: "^[A-Za-z0-9_-]+$",
			description: "Stable ID for this proposal batch. Reuse for retries; choose a new ID for a changed batch.",
		}),
		expected_revision: Type.Integer({
			minimum: 0,
			description: "Current canvas revision returned by get_canvas_overview or get_canvas_nodes",
		}),
		reason: Type.String({ minLength: 1, maxLength: 4000 }),
		anchor_node_id: Type.Optional(key),
		nodes: Type.Array(node, {
			maxItems: 50,
			description:
				"New cards. key identifies a card within this request; IDs, sizes and free positions are generated by the server. Use [] for an edges-only proposal.",
		}),
		edges: Type.Optional(
			Type.Array(
				Type.Object(
					{
						from: reference,
						to: reference,
						label: Type.String({ minLength: 1, maxLength: 120 }),
						evidence: Type.Optional(Type.String({ maxLength: 4000 })),
					},
					{ additionalProperties: false },
				),
				{ maxItems: 100 },
			),
		),
	},
	{ additionalProperties: false },
);
